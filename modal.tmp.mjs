import { chromium } from "@playwright/test";
const r = await fetch("http://localhost:4001/api/v1/auth/login", { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ username: "martin.amaro", password: "123456" }) });
const auth = await r.json();
const browser = await chromium.launch({ channel: "chrome" });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on("pageerror", (e) => errors.push(String(e).slice(0, 200)));
await page.addInitScript((a) => localStorage.setItem("ptnv_auth_v1", JSON.stringify({ token: a.token, refreshToken: a.refreshToken, user: a.user, loading: false, error: null })), auth);
await page.goto("http://localhost:5006/#/employees/disciplinary-reports", { waitUntil: "networkidle" });
await page.waitForTimeout(2600);
await page.getByRole("button", { name: "Nueva acta aquí" }).first().click();
await page.waitForTimeout(1400);
await page.screenshot({ path: "/tmp/rhshots/acta_modal.png", animations: "disabled" });
const txt = await page.evaluate(() => document.body.innerText.includes("Incidente") && document.body.innerText.includes("Detalle"));
console.log(JSON.stringify({ sections: txt, errors }));
await browser.close();
